  Future<String?> _resolveAccountForPaymentDeletion(
    DatabaseExecutor executor,
    Map<String, dynamic> payment,
    Map<String, dynamic> breakdown,
  ) async {
    final storedAccountId = breakdown['account_id']?.toString();
    if (storedAccountId != null && storedAccountId.isNotEmpty) {
      return storedAccountId;
    }

    final method = breakdown['method']?.toString();
    if (method == null || method.isEmpty) return null;

    final branchId = payment['branchId']?.toString();
    final accounts = await executor.query('accounts');
    final matches = accounts.where((account) {
      final accountType = account['type']?.toString();
      final accountBranchId = account['branchId']?.toString();
      if (method == 'cash') {
        return accountType == 'cash' && accountBranchId == branchId;
      }
      return accountType == 'bank' &&
          (accountBranchId == null || accountBranchId.isEmpty);
    }).toList();

    if (matches.isEmpty) return null;
    return matches.first['id']?.toString();
  }

