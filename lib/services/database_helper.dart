  Future<Database> get database async {
    if (_database != null) return _database!;
    _database = await _initDatabase();
    return _database!;
  }

  Future<Database> _initDatabase() async {
    Directory documentsDirectory = await getApplicationDocumentsDirectory();
    String path = join(documentsDirectory.path, 'semere_fashions.db');
    return await openDatabase(
      path,
      version: 41, // Bump database version
      onCreate: _onCreate,
      onUpgrade: _onUpgrade,
      onOpen: (db) async {
        await _ensureChangedFieldsColumns(db);
      },
    );
  }

  Future<void> _ensureChangedFieldsColumns(Database db) async {
    for (final table in _syncTrackedTables) {
      try {
        await db.execute('ALTER TABLE $table ADD COLUMN changed_fields TEXT');
      } catch (_) {
        // Column or table may already exist on upgraded installs.
      }
    }
  }

  Future<void> _ensureConflictColumns(Database db) async {
    try {
      await db.execute(
        'ALTER TABLE conflicts ADD COLUMN conflictingFields TEXT',
      );
    } catch (_) {
      // Existing installs may already have this column.
    }
  }

  Future<void> _seedDefaultRoles(Database db) async {
    final now = DateTime.now().millisecondsSinceEpoch;
    const roleNames = ['Admin', 'Manager', 'Sales', 'Tailor', 'Delivery'];
    for (final roleName in roleNames) {
      await db.insert('roles', {
        'name': roleName,
        'salary_type': 'commission',
        'default_monthly_salary': null,
        'created_at': now,
        'syncStatus': 'pending',
        'lastModified': now,
        'changed_fields': jsonEncode({
          'name': roleName,
          'salary_type': 'commission',
          'default_monthly_salary': null,
          'created_at': now,
        }),
      }, conflictAlgorithm: ConflictAlgorithm.ignore);
    }
  }

  Future<void> ensureDefaultRoles() async {
    final db = await database;
    final countResult = await db.rawQuery('SELECT COUNT(*) AS count FROM roles');
    final roleCount = (countResult.first['count'] as num?)?.toInt() ?? 0;
    if (roleCount == 0) {
      await _seedDefaultRoles(db);
    }
  }

