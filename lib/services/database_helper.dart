  Future<void> addPayment(
    String orderId,
    double amount,
    String method, {
    String type = 'payment',
    String? branchId,
    String? receivedBy,
    required String accountId,
  }) async {
    if (amount <= 0) {
      throw Exception('Amount must be greater than zero');
    }

    final account = await queryById('accounts', accountId);
    if (account == null) {
      throw Exception('Account not found');
    }

    final order = await queryById('orders', orderId);
    if (order == null) {
      throw Exception('Order not found');
    }

    final currentPaid = (order['paid_amount'] as num?)?.toDouble() ?? 0.0;
    final orderTotal = (order['totalAmount'] as num?)?.toDouble() ?? 0.0;

    double newPaid = currentPaid + amount;
    double tipAmount = 0.0;
    if (type == 'refund') {
      if (amount > currentPaid) {
        throw Exception('Refund cannot exceed paid amount');
      }
      newPaid = currentPaid - amount;
    } else if (newPaid > orderTotal) {
      tipAmount = newPaid - orderTotal;
      newPaid = orderTotal;
    }

    final transactionId = await insert('payment_transaction', {
      'orderId': orderId,
      'branchId': branchId ?? order['branchId'],
      'receivedBy': receivedBy,
      'date': DateTime.now().millisecondsSinceEpoch,
      'type': type,
      'amount': amount,
      'tip_amount': tipAmount,
      'deletedAt': 0,
    });
    await insert('payment_breakdown', {
      'id': '${transactionId}_$method',
      'payment_transaction_id': transactionId,
      'method': method,
      'amount': amount,
      'account_id': accountId,
    });
    await _updateAccountBalance(accountId, amount, type);
    await update('orders', {'id': orderId, 'paid_amount': newPaid});
  }

  Future<void> _updateAccountBalance(
    String accountId,
    double amount,
    String type,
  ) async {
    final account = await queryById('accounts', accountId);
    if (account == null) {
      throw Exception('Account not found');
    }
    final currentBalance =
        (account['current_balance'] as num?)?.toDouble() ?? 0.0;
    final newBalance = type == 'refund'
        ? currentBalance - amount
        : currentBalance + amount;
    await update('accounts', {'id': accountId, 'current_balance': newBalance});
  }

  Future<List<Map<String, dynamic>>> getPaymentsForOrder(String orderId) async {
    final db = await database;
    final rawPayments = List<Map<String, dynamic>>.from(
      await db.rawQuery(
        '''
        SELECT
          pt.*,
          pb.method AS method,
          pb.account_id AS accountId
        FROM payment_transaction pt
        LEFT JOIN payment_breakdown pb
          ON pb.payment_transaction_id = pt.id
        WHERE pt.orderId = ?
        ORDER BY pt.date DESC
        ''',
        [orderId],
      ),
    );
    final activePayments = _filterActivePayments(rawPayments);
    // Order details should favor complete transaction history. If every row is
    // filtered out by soft-delete flags, fall back to the raw rows so genuine
    // payment/refund history does not disappear.
    final payments = activePayments.isNotEmpty ? activePayments : rawPayments;
    payments.sort(
      (a, b) => ((b['date'] as num?)?.toInt() ?? 0).compareTo(
        (a['date'] as num?)?.toInt() ?? 0,
      ),
    );
    return payments;
  }

  Future<void> clearPaymentsForOrder(String orderId) async {
    final db = await database;
    final payments = await getPaymentsForOrder(orderId);
    await db.transaction((txn) async {
      for (final payment in payments) {
        final breakdowns = await txn.query(
          'payment_breakdown',
          where: 'payment_transaction_id = ?',
          whereArgs: [payment['id']],
        );
        for (final breakdown in breakdowns) {
          final accountId = await _resolveAccountForPaymentDeletion(
            txn,
            payment,
            breakdown,
          );
          if (accountId != null) {
            final accountRows = await txn.query(
              'accounts',
              where: 'id = ?',
              whereArgs: [accountId],
            );
            if (accountRows.isNotEmpty) {
              final currentBalance =
                  (accountRows.first['current_balance'] as num?)?.toDouble() ??
                  0.0;
              final amount = (breakdown['amount'] as num?)?.toDouble() ?? 0.0;
              final paymentType = payment['type']?.toString();
              final reversedBalance = paymentType == 'refund'
                  ? currentBalance + amount
                  : currentBalance - amount;
              await txn.update(
                'accounts',
                {'current_balance': reversedBalance},
                where: 'id = ?',
                whereArgs: [accountId],
              );
            }
          }
        }
        await txn.update(
          'payment_transaction',
          {
            'id': payment['id'],
            'deletedAt': DateTime.now().millisecondsSinceEpoch,
            'syncStatus': 'pending',
            'lastModified': DateTime.now().millisecondsSinceEpoch,
          },
          where: 'id = ?',
          whereArgs: [payment['id']],
        );
      }
      await txn.update(
        'orders',
        {
          'paid_amount': 0,
          'syncStatus': 'pending',
          'lastModified': DateTime.now().millisecondsSinceEpoch,
        },
        where: 'id = ?',
          whereArgs: [orderId],
      );
    });
  }

