    String monthKey,
  ) async {
    final db = await database;
    final employees = await db.rawQuery(
      '''
      SELECT u.id, u.name, u.monthly_salary
      FROM users u
      JOIN roles r ON u.role_id = r.id
      WHERE r.salary_type = 'monthly'
        AND u.status = 'active'
        AND u.monthly_salary IS NOT NULL
        AND u.id NOT IN (
          SELECT employeeId FROM employee_payments
          WHERE type = 'salary' AND for_month = ?
        )
      ''',
      [monthKey],
    );

    final now = DateTime.now().millisecondsSinceEpoch;
    for (final emp in employees) {
      await insert('employee_payments', {
        'id': '${emp['id']}_salary_$monthKey',
        'employeeId': emp['id']?.toString(),
        'employeeName': emp['name']?.toString(),
        'type': 'salary',
        'amount': (emp['monthly_salary'] as num?)?.toDouble() ?? 0.0,
        'month': monthKey,
        'for_month': monthKey,
        'status': 'pending',
        'datePaid': now,
        'createdAt': now,
        'notes': 'Generated salary for $monthKey',
      });
    }

    return employees.map((emp) => Map<String, dynamic>.from(emp)).toList();
  }

